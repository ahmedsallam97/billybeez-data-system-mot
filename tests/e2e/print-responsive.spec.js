const { test, expect } = require("@playwright/test");
const { PDFDocument } = require("pdf-lib");
const fs = require("node:fs");
const path = require("node:path");

test("roster prints to one unclipped A4 page and mobile content remains accessible", async ({ page }) => {
  test.setTimeout(120_000);
  const evidence = path.resolve("tmp/shell-theme-final/print-responsive");
  fs.mkdirSync(evidence, { recursive: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/operations/daily-preview?date=2026-09-29", { waitUntil: "networkidle" });
  await page.locator('input[type="date"]').fill("2026-09-29");
  await expect(page.locator(".daily-operations-poster")).toBeVisible();
  await page.screenshot({ path: path.join(evidence, "roster-desktop.png"), fullPage: true });
  await page.evaluate(() => { document.body.dataset.dailyPreviewPrint = "true"; });
  await page.emulateMedia({ media: "print" });
  const geometry = await page.locator(".daily-operations-poster").evaluate((node) => ({ width: node.getBoundingClientRect().width, scrollWidth: node.scrollWidth, height: node.getBoundingClientRect().height }));
  expect(geometry.scrollWidth).toBeLessThanOrEqual(Math.ceil(geometry.width) + 1);
  fs.writeFileSync(path.join(evidence, "roster-print-geometry.json"),JSON.stringify(await page.locator(".daily-operations-poster").evaluate(node=>[node,...node.children,...node.querySelectorAll(".ops-info-card")].map(item=>({class:item.className,top:item.getBoundingClientRect().top,width:item.getBoundingClientRect().width,height:item.getBoundingClientRect().height,columns:getComputedStyle(item).gridTemplateColumns,span:getComputedStyle(item).gridColumn,display:getComputedStyle(item).display}))),null,2));
  const pdfBytes = await page.pdf({ preferCSSPageSize: true, printBackground: true, displayHeaderFooter: false });
  fs.writeFileSync(path.join(evidence, "roster-a4.pdf"), pdfBytes);
  const pdf = await PDFDocument.load(pdfBytes);
  expect(pdf.getPageCount()).toBe(1);
  const size = pdf.getPage(0).getSize();
  expect(size.width).toBeCloseTo(595.28, 0);
  expect(size.height).toBeCloseTo(841.89, 0);
  await page.screenshot({ path: path.join(evidence, "roster-print-layout.png"), fullPage: true });
  await page.evaluate(() => { delete document.body.dataset.dailyPreviewPrint; });
  await page.emulateMedia({ media: "screen" });
  if(process.env.OPS_E2E_DESKTOP_ONLY==='1')return;
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator(".ops-roster-scroll")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(391);
  const scroll = page.locator(".ops-roster-scroll");
  expect(await scroll.evaluate((node) => node.scrollWidth > node.clientWidth)).toBeTruthy();
  await scroll.evaluate((node) => { node.scrollLeft = node.scrollWidth; });
  await page.screenshot({ path: path.join(evidence, "roster-mobile.png"), fullPage: true });
  await page.goto("/operations?tab=employees", { waitUntil: "networkidle" });
  await page.getByLabel("Employee file section", { exact: true }).selectOption("Timeline");
  await expect(page.getByRole("heading", { name: "Unified Timeline" })).toBeVisible();
  await expect(page.locator(".employee360-tabs")).not.toBeVisible();
  await page.screenshot({ path: path.join(evidence, "employee-mobile.png"), fullPage: true });
});
